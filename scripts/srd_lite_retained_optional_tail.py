"""Keep unused optional cast fields nullable across the retained internal continuation."""
import re

from .srd_lite_mass_cure_geometry import _effect_lists
from .srd_retained_spell_reactions import CHOICES, _rewrite_choices

TAIL = 'finish_srd_retained_cast_tail'
CONTEXT = '_retained_cast_tail_context'
OPTIONAL = {'target_distance':'number', 'origin_has_clear_path':'boolean'}
PRIVATE = {name:'_retained_optional_'+name for name in OPTIONAL}


def bind_cast_willing_default(runtime):
    """Omitted consent remains false when optional public choices reach required private handlers."""
    changed=[]
    for name,tool in runtime['tools'].items():
        for parameter in tool['parameters']:
            if parameter['name']=='all_targets_willing' and parameter.get('required') is False and 'default' not in parameter:
                if parameter.get('type')!='boolean':
                    raise ValueError('Keep the actual boolean consent contract')
                parameter['default']=False
                changed.append(name)
    return changed


def _replace_roots(value, replacements):
    """Rename only the qualified optional roots generated by the existing expression rewriter."""
    if isinstance(value,str):
        for old,new in replacements.items():
            value = re.sub(r'(?<![\w.])'+re.escape(old)+r'(?![\w])',new,value)
        return value
    if isinstance(value,list):
        return [_replace_roots(child,replacements) for child in value]
    if isinstance(value,dict):
        return {key:_replace_roots(child,replacements) for key,child in value.items()}
    return value


def _rewrite_nullable(value, *, inverse=False):
    """Reuse retained-tail expression rewriting while keeping nullable values in private context."""
    if inverse:
        return _replace_roots(value,{private:name for name,private in PRIVATE.items()})
    qualified = _rewrite_choices(value,set(OPTIONAL))
    return _replace_roots(qualified,{CHOICES+'.'+name:private for name,private in PRIVATE.items()})


def bind_retained_optional_tail(runtime):
    """Preserve optional checked inputs in the existing missing-value context capsule."""
    tools = runtime['tools']
    tail = tools[TAIL]
    declarations = {row['name']:row for row in tail['parameters']}
    for name, kind in OPTIONAL.items():
        row = declarations[name]
        public = next(p for p in tools['cast_spell']['parameters'] if p['name'] == name)
        if row != public or row.get('type') != kind or row.get('required',True) or row.get('default') is not None:
            raise ValueError('Keep the reviewed optional cast contract: '+name)
    calls, captures, seen = 0, 0, set()
    for tool in tools.values():
        effects = [effect for rows in _effect_lists(tool.get('effects',[])) for effect in rows]
        sites = [effect for effect in effects if effect.get('call') == TAIL]
        if not sites:
            continue
        expressions = {name:sites[0]['params'][name] for name in OPTIONAL}
        for name, expression in expressions.items():
            if not isinstance(expression,str) or not expression.startswith('{') or not expression.endswith('}'):
                raise ValueError('Keep the actual scalar optional field handoff: '+name)
        if any(any(effect['params'][name] != expressions[name] for name in OPTIONAL) for effect in sites):
            raise ValueError('One continuation owner must preserve the same checked optional inputs')
        for effect in effects:
            if id(effect) in seen:
                continue
            seen.add(id(effect))
            if effect.get('call') == TAIL:
                for name in OPTIONAL:
                    effect['params'].pop(name)
                calls += 1
            setting = effect.get('set',{})
            field = setting.get('field','')
            if field == CONTEXT or field.endswith('.retained_cast_context'):
                rows = setting['value']
                if not isinstance(rows,list) or any(row.get('key') == repr(private)
                    for row in rows for private in PRIVATE.values()):
                    raise ValueError('Keep the original missing-value context capsule')
                rows.extend({'key':repr(PRIVATE[name]),'missing':expression[1:-1]+' == null',
                    'value':expression[1:-1]} for name,expression in expressions.items())
                captures += 1
    if calls == 0 or captures < calls:
        raise ValueError('Capture every actual retained cast continuation before removing typed fields')
    tail['parameters'] = [row for row in tail['parameters'] if row['name'] not in OPTIONAL]
    original = tail['effects']
    qualified = _rewrite_nullable(original)
    if _rewrite_nullable(qualified,inverse=True) != original:
        raise ValueError('Optional choice factoring must reconstruct the exact original cast tail')
    tail['effects'] = qualified
    return {'calls':calls,'nullable_captures':captures}
