def slug(value: str) -> str:
    import re
    return re.sub(r"[^a-z0-9]+", "_", value.lower()).strip("_")

def parameter_id(specialty: str, node: str, family: str) -> str:
    return f"specialty.{slug(specialty)}.{slug(node)}.{family}"

unknown_rejected_rows = REJECTED_SPECIALTY_PARAMETER_ROWS.difference(
    SPECIALTY_PARAMETER_ROWS
)
if unknown_rejected_rows:
    raise RuntimeError(
        f"specialty audit rejects unknown parameter rows: {sorted(unknown_rejected_rows)}"
    )
unknown_deferred_rows = DEFERRED_NON_CUMULATIVE_PARAMETER_ROWS.difference(
    SPECIALTY_PARAMETER_ROWS
)
if unknown_deferred_rows:
    raise RuntimeError(
        "specialty audit defers unknown parameter rows: "
        f"{sorted(unknown_deferred_rows)}"
    )
if REJECTED_SPECIALTY_PARAMETER_ROWS & DEFERRED_NON_CUMULATIVE_PARAMETER_ROWS:
    raise RuntimeError("invalid and deferred specialty parameter audits overlap")

EXECUTABLE_SPECIALTY_PARAMETER_ROWS = tuple(
    row
    for row in SPECIALTY_PARAMETER_ROWS
    if row not in REJECTED_SPECIALTY_PARAMETER_ROWS
    and row not in DEFERRED_NON_CUMULATIVE_PARAMETER_ROWS
)
REJECTED_SPECIALTY_PARAMETER_IDS = frozenset(
    parameter_id(*row) for row in REJECTED_SPECIALTY_PARAMETER_ROWS
)
DEFERRED_SPECIALTY_PARAMETER_IDS = frozenset(
    parameter_id(*row) for row in DEFERRED_NON_CUMULATIVE_PARAMETER_ROWS
)

SPECIALTY_PARAMETERS_BY_NODE = {
    (specialty, node): tuple(
        parameter_id(candidate_specialty, candidate_node, family)
        for candidate_specialty, candidate_node, family in EXECUTABLE_SPECIALTY_PARAMETER_ROWS
        if (candidate_specialty, candidate_node) == (specialty, node)
    )
    for specialty, node, _family in EXECUTABLE_SPECIALTY_PARAMETER_ROWS
}
