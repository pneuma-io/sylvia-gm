"""Write `identifier_table.rs` beside this file from the frozen Python reference.

Run with the snapshot's own interpreter (CPython 3.12, Unicode 15.0.0), from the repository
root:

    .venv/Scripts/python.exe -I crates/sylvia-base/src/pystr/generate_identifier_table.py

`str.isidentifier()` tests each character on its own: the first must be a start character and
the rest continue characters. `START` is every `c` with `c.isidentifier()`, `CONTINUE` every
`c` with `("a" + c).isidentifier()`. Replacement templates use it for the group names of `g<name>` references.
This script is reference tooling for the port and is retired with the Python source.
"""

from __future__ import annotations

import sys
import unicodedata
from pathlib import Path

OUTPUT = Path(__file__).with_name("identifier_table.rs")


def ranges(test) -> list[tuple[int, int]]:
    found: list[tuple[int, int]] = []
    start = None
    for code in range(sys.maxunicode + 2):
        inside = code <= sys.maxunicode and test(chr(code))
        if inside and start is None:
            start = code
        elif not inside and start is not None:
            found.append((start, code - 1))
            start = None
    return found


def main() -> None:
    if unicodedata.unidata_version != "15.0.0":
        raise SystemExit(f"expected Unicode 15.0.0, this Python has {unicodedata.unidata_version}")
    start = ranges(str.isidentifier)
    cont = ranges(lambda c: ("a" + c).isidentifier())
    lines = [
        "// Generated by generate_identifier_table.py from CPython "
        f"{sys.version.split()[0]} (Unicode {unicodedata.unidata_version}). Do not edit.",
        "",
        "/// Inclusive ranges of code points that may start an identifier.",
        "pub(super) const START: &[(u32, u32)] = &[",
        *(f"    (0x{low:04X}, 0x{high:04X})," for low, high in start),
        "];",
        "",
        "/// Inclusive ranges of code points that may continue an identifier.",
        "pub(super) const CONTINUE: &[(u32, u32)] = &[",
        *(f"    (0x{low:04X}, 0x{high:04X})," for low, high in cont),
        "];",
        "",
    ]
    OUTPUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"{len(start)} start and {len(cont)} continue ranges -> {OUTPUT}")


if __name__ == "__main__":
    main()
