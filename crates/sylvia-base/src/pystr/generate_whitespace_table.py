"""Write `whitespace_table.rs` beside this file from the frozen Python reference.

Run with the snapshot's own interpreter (CPython 3.12.11, Unicode 15.0.0), from the
repository root:

    .venv/Scripts/python.exe -I crates/sylvia-base/src/pystr/generate_whitespace_table.py

The table is every character `str.isspace()` accepts, which is also what an argument-less
`str.strip()` removes. Python's set includes the information separators U+001C to U+001F,
which Rust's `char::is_whitespace` leaves out. This script is reference tooling for the port
and is retired with the Python source.
"""

from __future__ import annotations

import sys
import unicodedata
from pathlib import Path

OUTPUT = Path(__file__).with_name("whitespace_table.rs")


def main() -> None:
    if unicodedata.unidata_version != "15.0.0":
        raise SystemExit(f"expected Unicode 15.0.0, this Python has {unicodedata.unidata_version}")
    spaces = [code for code in range(sys.maxunicode + 1) if chr(code).isspace()]
    lines = [
        "// Generated by generate_whitespace_table.py from CPython "
        f"{sys.version.split()[0]} (Unicode {unicodedata.unidata_version}). Do not edit.",
        "",
        "#[cfg(test)]",
        f'pub(super) const UNICODE_VERSION: &str = "{unicodedata.unidata_version}";',
        "",
        "/// Every character `str.isspace()` accepts, sorted by code point.",
        "pub(super) static WHITESPACE: &[char] = &[",
        *(f"    '\\u{{{code:x}}}'," for code in spaces),
        "];",
        "",
    ]
    OUTPUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
