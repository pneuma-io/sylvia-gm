"""Write `digit_table.rs` and `printable_table.rs` beside this file from the frozen Python reference.

Run with the snapshot's own interpreter (CPython 3.12.11, Unicode 15.0.0), from the
repository root:

    .venv/Scripts/python.exe -I crates/sylvia-base/src/pystr/generate_number_tables.py

- `digit_table.rs`: the digit zero of every decimal (Nd) run. `int()` and `float()` turn any
  script's decimal digit into its ASCII digit before parsing; Rust's `char::to_digit` knows only
  ASCII.
- `printable_table.rs`: the ranges `str.isprintable()` accepts, which decide what `repr()`
  escapes.

This script is reference tooling for the port and is retired with the Python source.
"""

from __future__ import annotations

import sys
import unicodedata
from pathlib import Path

HERE = Path(__file__).parent


def header() -> list[str]:
    return [
        "// Generated by generate_number_tables.py from CPython "
        f"{sys.version.split()[0]} (Unicode {unicodedata.unidata_version}). Do not edit.",
        "",
        "#[cfg(test)]",
        f'pub(super) const UNICODE_VERSION: &str = "{unicodedata.unidata_version}";',
        "",
    ]


def main() -> None:
    if unicodedata.unidata_version != "15.0.0":
        raise SystemExit(f"expected Unicode 15.0.0, this Python has {unicodedata.unidata_version}")
    zeros = []
    for code in range(sys.maxunicode + 1):
        if unicodedata.decimal(chr(code), None) == 0:
            # Every Nd run in Unicode 15 is ten consecutive code points 0..9; check it.
            assert all(unicodedata.decimal(chr(code + n), None) == n for n in range(10)), hex(code)
            zeros.append(code)
    decimals = sum(1 for code in range(sys.maxunicode + 1) if unicodedata.decimal(chr(code), None) is not None)
    assert decimals == 10 * len(zeros), (decimals, len(zeros))
    lines = header() + [
        "/// The digit zero of every decimal (Nd) run; each run is ten consecutive code points.",
        "pub(super) const DECIMAL_ZEROS: &[u32] = &[",
        *(f"    0x{code:04X}," for code in zeros),
        "];",
        "",
    ]
    (HERE / "digit_table.rs").write_text("\n".join(lines), encoding="utf-8", newline="\n")

    ranges: list[tuple[int, int]] = []
    start = None
    for code in range(sys.maxunicode + 2):
        inside = code <= sys.maxunicode and chr(code).isprintable()
        if inside and start is None:
            start = code
        elif not inside and start is not None:
            ranges.append((start, code - 1))
            start = None
    lines = header() + [
        "/// Inclusive ranges of code points for which `str.isprintable()` is true.",
        "pub(super) const PRINTABLE: &[(u32, u32)] = &[",
        *(f"    (0x{low:04X}, 0x{high:04X})," for low, high in ranges),
        "];",
        "",
    ]
    (HERE / "printable_table.rs").write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"{len(zeros)} digit runs, {len(ranges)} printable ranges -> {HERE}")


if __name__ == "__main__":
    main()
