"""Write `ignorecase_table.rs` behind sylvia_base::pyre from the frozen Python reference.

Run with the snapshot's own interpreter (CPython 3.12.11, Unicode 15.0.0), from the
repository root:

    .venv/Scripts/python.exe -I crates/sylvia-base/src/pyre/generate_ignorecase_table.py

`re.IGNORECASE` on a `str` pattern compares characters through `_sre`'s own case functions,
not `str.lower()`: `_sre.unicode_tolower` (the simple lowercase mapping), `_sre.unicode_iscased`
and `re._casefix._EXTRA_CASES` (the characters that share a lowercase form, such as `i` and
`ı`). This writes all three: every character whose simple lowercase differs from itself, the
cased characters as ranges, and the extra cases. Rust's own case tables follow a newer Unicode
version, so the port reads Python's. Reference tooling, retired with the Python source.
"""

from __future__ import annotations

import _sre
import sys
import unicodedata
from pathlib import Path

import re._casefix as casefix

OUTPUT = Path(__file__).with_name("ignorecase_table.rs")


def code_points() -> list[int]:
    return [code for code in range(sys.maxunicode + 1) if not 0xD800 <= code <= 0xDFFF]


def ranges(codes: list[int]) -> list[tuple[int, int]]:
    result: list[tuple[int, int]] = []
    for code in codes:
        if result and result[-1][1] + 1 == code:
            result[-1] = (result[-1][0], code)
        else:
            result.append((code, code))
    return result


def main() -> None:
    if unicodedata.unidata_version != "15.0.0":
        raise SystemExit(f"expected Unicode 15.0.0, this Python has {unicodedata.unidata_version}")
    codes = code_points()
    lower = [(code, _sre.unicode_tolower(code)) for code in codes
             if _sre.unicode_tolower(code) != code]
    cased = ranges([code for code in codes if _sre.unicode_iscased(code)])
    extra = sorted(casefix._EXTRA_CASES.items())
    lines = [
        "// Generated by generate_ignorecase_table.py from CPython "
        f"{sys.version.split()[0]} (Unicode {unicodedata.unidata_version}). Do not edit.",
        "",
        "#[cfg(test)]",
        f'pub(super) const UNICODE_VERSION: &str = "{unicodedata.unidata_version}";',
        "",
        "/// `_sre.unicode_tolower`: every character whose simple lowercase differs, sorted.",
        "pub(super) static LOWER: &[(char, char)] = &[",
        *[f"    ('\\u{{{code:x}}}', '\\u{{{mapped:x}}}')," for code, mapped in lower],
        "];",
        "",
        "/// `_sre.unicode_iscased`: the cased characters, as sorted inclusive ranges.",
        "pub(super) static CASED: &[(char, char)] = &[",
        *[f"    ('\\u{{{start:x}}}', '\\u{{{end:x}}}')," for start, end in cased],
        "];",
        "",
        "/// `re._casefix._EXTRA_CASES`: a lowercase form and the others that share it, sorted.",
        "pub(super) static EXTRA_CASES: &[(char, &[char])] = &[",
        *["    ('\\u{%x}', &[%s])," % (code, ", ".join(f"'\\u{{{other:x}}}'" for other in others))
          for code, others in extra],
        "];",
        "",
    ]
    OUTPUT.write_bytes("\n".join(lines).encode("utf-8"))
    print(len(lower), "lower,", len(cased), "cased ranges,", len(extra), "extra cases")


if __name__ == "__main__":
    main()
