"""Export builder/_prompts.py's literal text as builder_prompt_text.rs, byte for byte.

Run from the repository root with the snapshot's interpreter:

    .venv/Scripts/python.exe -I crates/sylvia-app/src/generate_builder_prompt_text.py

The Builder prompt is model-read, so its text is copied, never retyped. This reads the
function's syntax tree (the parser has already joined each implicit concatenation into one
constant) and writes each constant piece as a Rust string literal. The Rust module supplies
only the joins. This script is reference tooling for the port and is retired with the Python
source.
"""

from __future__ import annotations

import ast
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
SOURCE = ROOT / "src/sylvia_gm/builder/_prompts.py"
OUTPUT = Path(__file__).with_name("builder_prompt_text.rs")
NEWLINE = chr(10)
BACKSLASH = chr(92)


def rust_literal(text: str) -> str:
    out = []
    for character in text:
        if character == BACKSLASH:
            out.append(BACKSLASH * 2)
        elif character == '"':
            out.append(BACKSLASH + '"')
        elif character == NEWLINE:
            out.append(BACKSLASH + "n")
        elif ord(character) < 32 or ord(character) == 127:
            out.append(BACKSLASH + "u{" + format(ord(character), "x") + "}")
        else:
            out.append(character)
    return '"' + "".join(out) + '"'


def main() -> None:
    tree = ast.parse(SOURCE.read_text(encoding="utf-8"))
    function = next(node for node in tree.body if isinstance(node, ast.FunctionDef))
    pieces: dict[str, str] = {}
    for node in ast.walk(function):
        if isinstance(node, ast.Assign) and isinstance(node.targets[0], ast.Name):
            name, value = node.targets[0].id, node.value
            if name == "greeting":
                pieces["GREETING"] = value.value
            elif name == "options_block" and isinstance(value, ast.BinOp):
                left = value.left
                assert isinstance(left, ast.BinOp) and isinstance(left.left, ast.Constant)
                assert isinstance(value.right, ast.Constant)
                pieces["OPTIONS_HEADER"] = left.left.value
                pieces["OPTIONS_HEADER_END"] = value.right.value
            elif name == "preamble":
                parts = value.values
                kinds = [type(part).__name__ for part in parts]
                assert kinds == ["Constant", "FormattedValue", "Constant", "FormattedValue", "Constant"], kinds
                assert [part.value.id for part in parts if isinstance(part, ast.FormattedValue)] == [
                    "options_block", "greeting"]
                pieces["PREAMBLE_HEAD"] = parts[0].value
                pieces["PREAMBLE_MIDDLE"] = parts[2].value
                pieces["PREAMBLE_TAIL"] = parts[4].value
        elif (isinstance(node, ast.AugAssign) and isinstance(node.target, ast.Name)
              and node.target.id == "options_block" and isinstance(node.value, ast.Constant)):
            pieces["OPTIONS_WARNING"] = node.value.value
    order = ["GREETING", "OPTIONS_HEADER", "OPTIONS_HEADER_END", "OPTIONS_WARNING", "PREAMBLE_HEAD",
             "PREAMBLE_MIDDLE", "PREAMBLE_TAIL"]
    assert sorted(pieces) == sorted(order), sorted(pieces)
    lines = [
        "//! Generated by `generate_builder_prompt_text.py` from `builder/_prompts.py`; do not edit.",
        "//! The Builder prompt is model-read, so its text is the Python source's, byte for byte.",
        "",
    ]
    for name in order:
        lines.append(f"pub(crate) const {name}: &str = {rust_literal(pieces[name])};")
    OUTPUT.write_text(NEWLINE.join(lines) + NEWLINE, encoding="utf-8", newline=NEWLINE)
    print({name: len(pieces[name]) for name in order})


if __name__ == "__main__":
    main()
