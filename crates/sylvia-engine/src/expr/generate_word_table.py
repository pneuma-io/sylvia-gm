"""Write `word_table.rs` beside this file from the frozen Python reference.

Run with the snapshot's own interpreter (CPython 3.12.11, Unicode 15.0.0), from the
repository root:

    .venv/Scripts/python.exe -I crates/sylvia-engine/src/expr/generate_word_table.py

The table is every character Python's `re` treats as `\\w` in a `str` pattern. The expression
tokenizer's keywords end in `\\b` (`true\\b`, `and\\b`, ...), so whether a keyword is followed by
a word character decides between a keyword and an identifier, and `\\w` includes letters and
digits of every script. This script is reference tooling for the port and is retired with the
Python source.
"""

from __future__ import annotations

import re
import sys
import unicodedata
from pathlib import Path

OUTPUT = Path(__file__).with_name("word_table.rs")


def main() -> None:
    if unicodedata.unidata_version != "15.0.0":
        raise SystemExit(f"expected Unicode 15.0.0, this Python has {unicodedata.unidata_version}")
    word = re.compile(r"\w")
    ranges: list[tuple[int, int]] = []
    start = None
    for code in range(sys.maxunicode + 2):
        inside = code <= sys.maxunicode and word.match(chr(code)) is not None
        if inside and start is None:
            start = code
        elif not inside and start is not None:
            ranges.append((start, code - 1))
            start = None
    lines = [
        "// Generated by generate_word_table.py from CPython "
        f"{sys.version.split()[0]} (Unicode {unicodedata.unidata_version}). Do not edit.",
        "",
        "#[cfg(test)]",
        f'pub(super) const UNICODE_VERSION: &str = "{unicodedata.unidata_version}";',
        "",
        "/// Inclusive ranges of code points that `re`'s `\\w` matches in a `str` pattern.",
        "pub(super) const WORD: &[(u32, u32)] = &[",
        *(f"    (0x{low:04X}, 0x{high:04X})," for low, high in ranges),
        "];",
        "",
    ]
    OUTPUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"{len(ranges)} word ranges -> {OUTPUT}")


if __name__ == "__main__":
    main()
