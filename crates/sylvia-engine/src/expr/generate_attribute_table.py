"""Write `attribute_table.rs` beside this file from the frozen Python reference.

Run with the snapshot's own interpreter (CPython 3.12.11), from the repository root:

    .venv/Scripts/python.exe -I crates/sylvia-engine/src/expr/generate_attribute_table.py

The evaluator's `_traverse_field` reads `getattr(value, field)` when `hasattr` says the
attribute exists on a value that is not a dict, list, tuple or None. For `str`, `int`, `float`
and `bool` that is a fixed set of names; this table lists them (dunder names excepted, see
`differences.md`) and says which are data (`int.real`) and which are methods. This script is
reference tooling for the port and is retired with the Python source.
"""

from __future__ import annotations

import sys
from pathlib import Path

OUTPUT = Path(__file__).with_name("attribute_table.rs")
SAMPLES = {"str": "a", "int": 1, "float": 1.5, "bool": True}


def main() -> None:
    lines = [
        f"// Generated by generate_attribute_table.py from CPython {sys.version.split()[0]}. Do not edit.",
        "",
        "/// `(type, attribute, is_method)` for every non-dunder attribute `hasattr` finds on an",
        "/// instance of `str`, `int`, `float` or `bool`, sorted by type then name.",
        "pub(super) const ATTRIBUTES: &[(&str, &str, bool)] = &[",
    ]
    for type_name, sample in SAMPLES.items():
        for name in sorted(dir(sample)):
            if name.startswith("__"):
                continue
            lines.append(f'    ("{type_name}", "{name}", {"true" if callable(getattr(sample, name)) else "false"}),')
    lines += ["];", ""]
    OUTPUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"{len(lines) - 7} attributes -> {OUTPUT}")


if __name__ == "__main__":
    main()
