"""Write `alnum_table.rs` beside this file from the frozen Python reference.

Run with the snapshot's own interpreter (CPython 3.12, Unicode 15.0.0), from the repository
root:

    .venv/Scripts/python.exe -I crates/sylvia-engine/src/ruleset/generate_alnum_table.py

The table is every character `str.isalnum()` accepts, which the Ruleset validator uses for
model-decision preparation identifiers. This script is reference tooling for the port and is
retired with the Python source.
"""

from __future__ import annotations

import sys
import unicodedata
from pathlib import Path

OUTPUT = Path(__file__).with_name("alnum_table.rs")


def main() -> None:
    if unicodedata.unidata_version != "15.0.0":
        raise SystemExit(f"expected Unicode 15.0.0, this Python has {unicodedata.unidata_version}")
    ranges: list[tuple[int, int]] = []
    start = None
    for code in range(sys.maxunicode + 2):
        inside = code <= sys.maxunicode and chr(code).isalnum()
        if inside and start is None:
            start = code
        elif not inside and start is not None:
            ranges.append((start, code - 1))
            start = None
    lines = [
        "// Generated by generate_alnum_table.py from CPython "
        f"{sys.version.split()[0]} (Unicode {unicodedata.unidata_version}). Do not edit.",
        "",
        "/// Inclusive ranges of code points for which `str.isalnum()` is true.",
        "pub(super) const ALNUM: &[(u32, u32)] = &[",
        *(f"    (0x{low:04X}, 0x{high:04X})," for low, high in ranges),
        "];",
        "",
    ]
    OUTPUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"{len(ranges)} ranges -> {OUTPUT}")


if __name__ == "__main__":
    main()
