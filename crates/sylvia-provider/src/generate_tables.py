"""Write the provider tables Rust copies from the frozen Python reference.

Run with the snapshot's own interpreter, from the repository root:

    .venv/Scripts/python.exe crates/sylvia-provider/src/generate_tables.py

- `config/presets_table.rs`: `config/provider_settings._PROVIDER_PRESETS`, text the player reads.
- `model_facts_table.rs`: `provider/_model_facts` (facts, OpenAI aliases, documented defaults,
  OpenCode routes).

Generated files are kept exactly as written here (`#[rustfmt::skip]`). Reference tooling only;
retired with the Python source.
"""

from __future__ import annotations

from pathlib import Path

from sylvia_gm.config import provider_settings
from sylvia_gm.provider import _model_facts as facts

HERE = Path(__file__).parent
HEADER = "// Generated by src/generate_tables.py from the Python reference. Do not edit.\n\n"
PRESET_KEYS = (
    "name", "mode", "base_url", "credential_required", "endpoint_editable", "default_transport",
    "launch_hint", "setup_hint", "setup_url",
)
CATALOG_KEYS = (
    "name", "context_window", "max_output_tokens", "transport", "supports_tools", "supports_streaming",
    "supported_reasoning_efforts", "default_reasoning_effort", "documented_source", "documented_at",
)


def rust_str(text: str) -> str:
    out = ['"']
    for ch in text:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif " " <= ch <= "~":
            out.append(ch)
        else:
            out.append("\\u{%x}" % ord(ch))
    out.append('"')
    return "".join(out)


def rust_opt_str(value) -> str:
    return "None" if value is None else f"Some({rust_str(value)})"


def rust_efforts(value) -> str:
    return "None" if value is None else "Some(&[" + ", ".join(rust_str(v) for v in value) + "])"


def presets() -> str:
    lines = [HEADER, "use super::Preset;\n\n", "pub(crate) const PRESETS: &[Preset] = &[\n"]
    for preset_id, preset in provider_settings._PROVIDER_PRESETS.items():
        keys = [key for key in PRESET_KEYS if key in preset]
        assert list(preset) == keys, (preset_id, list(preset))
        lines.append(
            "    Preset {"
            f" id: {rust_str(preset_id)},"
            f" name: {rust_str(preset['name'])},"
            f" mode: {rust_str(preset['mode'])},"
            f" base_url: {rust_str(preset['base_url'])},"
            f" credential_required: {str(preset['credential_required']).lower()},"
            f" endpoint_editable: {str(preset['endpoint_editable']).lower()},"
            f" default_transport: {rust_str(preset['default_transport'])},"
            f" launch_hint: {rust_opt_str(preset.get('launch_hint'))},"
            f" setup_hint: {rust_str(preset['setup_hint'])},"
            f" setup_url: {rust_opt_str(preset.get('setup_url'))},"
            " },\n"
        )
    lines.append("];\n")
    return "".join(lines)


def catalog(entry: dict) -> str:
    for key in entry:
        assert key in CATALOG_KEYS, key
    def opt_int(key):
        return "None" if entry.get(key) is None else f"Some({entry[key]})"
    def opt_bool(key):
        return "None" if key not in entry else f"Some({str(entry[key]).lower()})"
    effort = (
        "Absent" if "default_reasoning_effort" not in entry
        else "Present(None)" if entry["default_reasoning_effort"] is None
        else f"Present(Some({rust_str(entry['default_reasoning_effort'])}))"
    )
    return (
        "Catalog {"
        f" name: {rust_opt_str(entry.get('name'))},"
        f" context_window: {opt_int('context_window')},"
        f" max_output_tokens: {opt_int('max_output_tokens')},"
        f" transport: {rust_opt_str(entry.get('transport'))},"
        f" supports_tools: {opt_bool('supports_tools')},"
        f" supports_streaming: {opt_bool('supports_streaming')},"
        f" supported_reasoning_efforts: {rust_efforts(entry.get('supported_reasoning_efforts'))},"
        f" default_reasoning_effort: {effort},"
        f" documented_source: {rust_opt_str(entry.get('documented_source'))},"
        f" documented_at: {rust_opt_str(entry.get('documented_at'))},"
        " }"
    )


def model_facts() -> str:
    lines = [HEADER, "use super::{Catalog, ModelFacts, Present::*};\n\n"]
    lines.append("pub(crate) const FACTS: &[((&str, &str), ModelFacts)] = &[\n")
    for (route, model_id), fact in facts._MODEL_FACTS.items():
        catalog_text = "None" if not fact.catalog else f"Some({catalog(dict(fact.catalog))})"
        lines.append(
            f"    (({rust_str(route)}, {rust_str(model_id)}), ModelFacts {{"
            f" efforts: {rust_efforts(fact.efforts)},"
            f" default_effort: {rust_str(fact.default_effort)},"
            f" forced_tool_choice: {str(fact.forced_tool_choice).lower()},"
            f" temperature: {str(fact.temperature).lower()},"
            f" binds_thinking: {str(fact.binds_thinking).lower()},"
            f" tool_changes: {str(fact.tool_changes).lower()},"
            f" fast: {str(fact.fast).lower()},"
            f" flex: {str(fact.flex).lower()},"
            f" context_window: {'None' if fact.context_window is None else f'Some({fact.context_window})'},"
            f" gm_narration_hint: {str(fact.gm_narration_hint).lower()},"
            f" catalog: {catalog_text},"
            " }),\n"
        )
    lines.append("];\n\n")
    lines.append("pub(crate) const OPENAI_ALIASES: &[(&str, &str)] = &[\n")
    for alias, target in facts._OPENAI_ALIASES.items():
        lines.append(f"    ({rust_str(alias)}, {rust_str(target)}),\n")
    lines.append("];\n\n")
    lines.append("/// `_DEFAULTS` keys, in insertion order (`documented_model_ids()`).\n")
    lines.append("pub(crate) const DOCUMENTED_IDS: &[(&str, &str)] = &[\n")
    for route, model_id in facts._DEFAULTS:
        lines.append(f"    ({rust_str(route)}, {rust_str(model_id)}),\n")
    lines.append("];\n\n")
    lines.append("/// `_OPENCODE_ROUTES`: (preset, exact?, identities, protocol), in order.\n")
    lines.append("pub(crate) const OPENCODE_ROUTES: &[(&str, bool, &[&str], &str)] = &[\n")
    for preset, routes in facts._OPENCODE_ROUTES.items():
        for mode, identities, protocol in routes:
            ids = ", ".join(rust_str(i) for i in identities)
            lines.append(f"    ({rust_str(preset)}, {str(mode == 'exact').lower()}, &[{ids}], {rust_str(protocol)}),\n")
    lines.append("];\n")
    return "".join(lines)


def main() -> int:
    (HERE / "config" / "presets_table.rs").write_text(presets(), encoding="utf-8", newline="\n")
    (HERE / "model_facts_table.rs").write_text(model_facts(), encoding="utf-8", newline="\n")
    print("written")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
