"""Write `cp437_table.rs` beside this file from the frozen Python reference.

Run with the snapshot's own interpreter, from the repository root:

    .venv/Scripts/python.exe -I crates/sylvia-domain/src/package_archive/generate_cp437_table.py

`zipfile` decodes a member name without the UTF-8 flag as cp437; bytes below 0x80 are ASCII
and the table holds the 128 characters for 0x80 to 0xFF. This script is reference tooling for
the port and is retired with the Python source.
"""

from __future__ import annotations

from pathlib import Path

OUTPUT = Path(__file__).with_name("cp437_table.rs")


def main() -> None:
    upper = bytes(range(0x80, 0x100)).decode("cp437")
    assert bytes(range(0x80)).decode("cp437") == bytes(range(0x80)).decode("ascii")
    rows = [f"    '\\u{{{ord(c):x}}}'," for c in upper]
    OUTPUT.write_text(
        "// Generated by generate_cp437_table.py from CPython's cp437 codec. Do not edit.\n\n"
        "/// `bytes([0x80 + i]).decode(\"cp437\")` for `i` in 0..128.\n"
        "pub(super) static CP437_HIGH: [char; 128] = [\n" + "\n".join(rows) + "\n];\n",
        encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
