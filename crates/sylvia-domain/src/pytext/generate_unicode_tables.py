"""Write the Unicode tables behind sylvia_domain::pytext from the frozen Python reference.

Run with the snapshot's own interpreter (CPython 3.12.11, Unicode 15.0.0), from the
repository root:

    .venv/Scripts/python.exe crates/sylvia-domain/src/pytext/generate_unicode_tables.py

It writes `unicode_tables.rs` beside itself: the characters `str.isspace()` accepts, and every
character whose `str.casefold()` or `str.upper()` differs from itself. Rust's own tables follow
a newer Unicode version and a different whitespace definition, so the port reads Python's.
This script is reference tooling for the port and is retired with the Python source.
"""

from __future__ import annotations

import sys
import unicodedata
from pathlib import Path

OUTPUT = Path(__file__).with_name("unicode_tables.rs")


def rust_str(text: str) -> str:
    return '"' + "".join(f"\\u{{{ord(c):x}}}" for c in text) + '"'


def mapping(name: str, method: str) -> list[str]:
    rows = []
    for code in range(sys.maxunicode + 1):
        if 0xD800 <= code <= 0xDFFF:
            continue
        character = chr(code)
        mapped = getattr(character, method)()
        if mapped != character:
            rows.append(f"    ('\\u{{{code:x}}}', {rust_str(mapped)}),")
    return [
        f"/// Every character whose `str.{method}()` differs from itself, sorted by code point.",
        f"pub(crate) static {name}: &[(char, &str)] = &[",
        *rows,
        "];",
    ]


def main() -> None:
    if unicodedata.unidata_version != "15.0.0":
        raise SystemExit(f"expected Unicode 15.0.0, this Python has {unicodedata.unidata_version}")
    spaces = [code for code in range(sys.maxunicode + 1) if chr(code).isspace()]
    lines = [
        "// Generated by generate_unicode_tables.py from CPython "
        f"{sys.version.split()[0]} (Unicode {unicodedata.unidata_version}). Do not edit.",
        "",
        f'pub(crate) const UNICODE_VERSION: &str = "{unicodedata.unidata_version}";',
        "",
        "/// Every character `str.isspace()` accepts (what `str.strip()` removes).",
        "pub(crate) static WHITESPACE: &[char] = &[",
        *(f"    '\\u{{{code:x}}}'," for code in spaces),
        "];",
        "",
        *mapping("CASEFOLD", "casefold"),
        "",
        *mapping("UPPER", "upper"),
        "",
    ]
    OUTPUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
