"""Export the installed content definitions from the frozen Python reference as data.

Run with the snapshot's own interpreter, from the repository root:

    .venv/Scripts/python.exe -I crates/sylvia-domain/src/content/generate_definitions.py

`domain/content_definitions.py` assembles 24 definitions (schema, example, requirement notes,
file) from the `_content_schema_*` modules. Their text is read by authors and by the model
(the Builder's content-definition tool returns it), so the Rust port loads exactly these
values: key order, integers versus floats and every string are kept. One JSON file per
definition goes in `definitions/`, `definitions.rs` lists them in catalogue order, and
`definitions/package_runtime.procedural.json` is the runtime procedural definition.
This script is reference tooling for the port and is retired with the Python source.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

HERE = Path(__file__).parent
DATA = HERE / "definitions"


def dump(value: object) -> str:
    # ASCII escapes keep every character visible in review; the parsed value is unchanged.
    return json.dumps(value, indent=1, ensure_ascii=True) + "\n"


def main() -> None:
    sys.path.insert(0, str(HERE.parents[3] / "src"))
    from sylvia_gm.domain import content_definitions
    from sylvia_gm.domain._content_schema_runtime import RUNTIME_PROCEDURAL_DEFINITION

    DATA.mkdir(exist_ok=True)
    for stale in DATA.glob("*.json"):
        stale.unlink()
    names = []
    for name, (schema, example, notes, file) in content_definitions._DEFINITIONS.items():
        names.append(name)
        record = {"schema": schema, "example": example, "notes": list(notes), "file": file}
        (DATA / f"{name}.json").write_text(dump(record), encoding="utf-8", newline="\n")
    (DATA / "package_runtime.procedural.json").write_text(
        dump(RUNTIME_PROCEDURAL_DEFINITION), encoding="utf-8", newline="\n")
    rows = "\n".join(f'    ("{name}", include_str!("definitions/{name}.json")),' for name in names)
    (HERE / "definitions.rs").write_text(
        "// Generated by generate_definitions.py from the Python snapshot. Do not edit.\n"
        "\n"
        "/// `(name, JSON)` for every installed definition, in `_DEFINITIONS` order.\n"
        "pub(super) static DEFINITIONS: &[(&str, &str)] = &[\n"
        f"{rows}\n"
        "];\n"
        "\n"
        "/// `RUNTIME_PROCEDURAL_DEFINITION`, returned with the `package_runtime` definition.\n"
        "pub(super) static PACKAGE_RUNTIME_PROCEDURAL: &str =\n"
        '    include_str!("definitions/package_runtime.procedural.json");\n',
        encoding="utf-8", newline="\n",
    )


if __name__ == "__main__":
    main()
